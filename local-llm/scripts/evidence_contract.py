CATALOG = catalog()


def canonical(name, vocabulary=None):
    for key, values in (CATALOG if vocabulary is None else vocabulary).items():
        if name.casefold() in {x.casefold() for x in values}:
            return key
    return name


def candidates(blocks, vocabulary=None):
    found = {}
    for index, block in enumerate(blocks, 1):
        text = block["text"]
        matches = []
        for name, aliases in (CATALOG if vocabulary is None else vocabulary).items():
            for alias in aliases:
                pattern = r"(?<![A-Za-z0-9_+#.])" + re.escape(alias) + r"(?![A-Za-z0-9_+#])"
                for m in re.finditer(pattern, text, re.I):
                    # Avoid interpreting E-R diagrams and R&D as the R language.
                    if name == 'R' and (re.search(r'[A-Za-z]-$', text[:m.start()]) or
                                        re.match(r'\s*&\s*D\b', text[m.end():], re.I)):
                        continue
                    if name == 'Assembly':
                        nearby = text[max(0, m.start()-80):m.end()+80]
                        mechanical = re.search(r'SolidWorks|부품|파트|모델링|간섭', nearby, re.I)
                        programming = re.search(r'명령어|레지스터|스택|어셈블리\s*언어|Assembly\s+language', nearby, re.I)
                        if mechanical and not programming:
                            continue
                    matches.append((m.start(), m.end(), name, m.group()))
        occupied = []
        for a, b, name, quote in sorted(matches, key=lambda x: (-(x[1]-x[0]), x[0], x[2])):
            if any(a < y and b > x for x, y in occupied):
                continue
            occupied.append((a, b))
            found.setdefault(name, []).append({"block": index, "start": a, "end": b, "quote": quote})
    order = sorted(found, key=lambda n: min((m["block"], m["start"]) for m in found[n]))
    return [{"name": name, "mentions": sorted(found[name], key=lambda m: (m["block"], m["start"]))} for name in order]


def request(blocks, vocabulary=None):
    return {"resume": [{"id": i+1, "text": b["text"]} for i, b in enumerate(blocks)], "candidates": candidates(blocks, vocabulary)}


def prompt_request(req):
    return {"resume": req["resume"], "candidates": [{"name": c["name"], "blocks": sorted({m["block"] for m in c["mentions"]})} for c in req["candidates"]]}


def validate(text, req):
    value = json.loads(text)
    if not isinstance(value, dict) or set(value) != {"states"}:
        raise ValueError("Only states is allowed")
    states = value["states"]
    if not isinstance(states, list) or len(states) != len(req["candidates"]):
        raise ValueError("Exactly one state per candidate required")
    if any(type(s) is not int or not 0 <= s < len(STATES) for s in states):
        raise ValueError("State must be an integer from 0 to 6")
    return states


def project(req, states, vocabulary=None):
    """Only return source-verified names, preserving all excluded decisions too."""
    validate(json.dumps({"states": states}), req)
    if req["candidates"] != candidates(req["resume"], vocabulary):
        raise ValueError("Candidates must exactly match source extraction")
    all_decisions, technologies, skills = [], [], {}
    mapping = {"Python": "python", "Docker": "docker", "TypeScript": "typescript", "React": "react", "React Native": "react",
               **{n: "sql" for n in ("SQL", "MySQL", "SQLite", "PostgreSQL", "MariaDB", "Oracle")}}
    for candidate, state in zip(req["candidates"], states, strict=True):
        # Rebuild and compare mentions so caller-supplied candidates cannot invent evidence.
        for m in candidate["mentions"]:
            text = req["resume"][m["block"]-1]["text"]
            if text[m["start"]:m["end"]] != m["quote"] or canonical(m["quote"], vocabulary) != candidate["name"]:
                raise ValueError("Evidence does not match source")
        item = {**candidate, "state": STATES[state]}
        all_decisions.append(item)
        if state <= 2:
            technologies.append({**item, "level": ("applied", "learning", "mentioned")[state]})
            sid = mapping.get(candidate["name"])
            if sid:
                skills[sid] = min(skills.get(sid, 2), state)
    return {"technologies": technologies, "skills": [{"skillId": k, "level": ("applied", "learning", "mentioned")[v]} for k, v in sorted(skills.items())],
            "decisions": all_decisions, "scope": "technology-backed competencies only; source presence is not proof of actual competence"}


def score(text, req, gold, finish="stop"):
    targets = gold["states"]
    try:
        states = validate(text, req)
        if finish != "stop":
            raise ValueError("Truncated output")
        valid, error = True, None
    except (ValueError, TypeError, KeyError) as exc:
        states, valid, error = [], False, str(exc)
    wanted = {(c["name"], s) for c, s in zip(req["candidates"], targets, strict=True) if s <= 2}
    got = {(c["name"], s) for c, s in zip(req["candidates"], states) if s <= 2}
    return {"valid": valid, "error": error, "correct_states": sum(a == b for a, b in zip(states, targets)), "candidates": len(targets),
            "tp": len(wanted & got), "fp": len(got-wanted), "fn": len(wanted-got),
            "false_attribution": sum(g >= 3 and p <= 2 for p, g in zip(states, targets)),
            "exact": valid and states == targets}


def summarize(records, field="constrained"):
    scores = [r[field]["score"] for r in records]
    totals = {k: sum(s[k] for s in scores) for k in ("correct_states", "candidates", "tp", "fp", "fn", "false_attribution")}
    a, b, c = (totals[k] for k in ("tp", "fp", "fn"))
    return {**totals, "examples": len(scores), "valid": sum(s["valid"] for s in scores), "exact": sum(s["exact"] for s in scores),
            "precision": a/(a+b) if a+b else 0., "recall": a/(a+c) if a+c else 0., "f1": 2*a/(2*a+b+c) if 2*a+b+c else 0.,
            "state_accuracy": totals["correct_states"]/totals["candidates"] if totals["candidates"] else 0.}
